"""Numbered menu choices that the game glues together before drawing.

Some games build the choice label in their own ``choice`` screen, e.g.
``str(num) + ". " + item.caption``. Ren'Py translates a text as a whole, so
``"1. Enter Common Room"`` never matches the ``old "Enter Common Room"`` entry
and the choice stays in the source language, whatever the tl file says.

Native TLID mode keeps the game on stock Ren'Py (no runtime hook, no
``strings.json``), so this is handled narrowly: the game's scripts are scanned
and a few-line ``config.replace_text`` wrapper is written *only* when such a
concatenation exists. It looks at the first character first, so text that does
not start with a digit costs one comparison.
"""

from __future__ import annotations

import os
import re
import zlib
from pathlib import Path
from typing import Iterable

HOOK_FILENAME = "zzz_rl_numbered_choices.rpy"

# Every way of gluing a number to the caption before the text is drawn:
# ``str(n) + ". " + x.caption``, ``"%d. %s" % (n, x.caption)``,
# ``"{}. {}".format(n, x.caption)`` and ``f"{n}. {x.caption}"``.
_PATTERNS = tuple(
    re.compile(p) for p in (
        r"""\+\s*["']\.\s?["']\s*\+\s*[\w.\[\]]*caption""",
        r"""["']%d\.\s?%s["']\s*%\s*\([^)]*caption""",
        r"""["']\{\}\.\s?\{\}["']\s*\.format\([^)]*caption""",
        r"""\bf["']\{[^}]+\}\.\s?\{[\w.\[\]]*caption[^}]*\}""",
    )
)

_SKIP_DIRS = {"tl", "renpy", "cache", "saves", "audio", "images", "fonts", "gui"}
_MAX_SOURCE_BYTES = 8 * 1024 * 1024


def _text_matches(text: str) -> bool:
    if "caption" not in text:
        return False
    return any(p.search(text) for p in _PATTERNS)


def _rpyc_chunks(data: bytes) -> Iterable[bytes]:
    """Yield the decompressed slots of a .rpyc (RENPY RPC2) file."""
    if not data.startswith(b"RENPY RPC2"):
        yield data
        return
    pos = 10
    while pos + 12 <= len(data):
        slot = int.from_bytes(data[pos:pos + 4], "little")
        start = int.from_bytes(data[pos + 4:pos + 8], "little")
        length = int.from_bytes(data[pos + 8:pos + 12], "little")
        if slot == 0:
            break
        try:
            yield zlib.decompress(data[start:start + length])
        except Exception:
            break
        pos += 12


def _iter_game_scripts(game_dir: Path):
    for root, dirs, files in os.walk(game_dir):
        dirs[:] = [d for d in dirs if d.lower() not in _SKIP_DIRS and not d.startswith(".")]
        rpy_stems = {f[:-4] for f in files if f.endswith(".rpy")}
        for name in files:
            low = name.lower()
            if low.startswith("zzz_"):
                continue
            if low.endswith(".rpy"):
                yield Path(root) / name
            elif low.endswith(".rpyc") and name[:-1] not in {s + ".rpy" for s in rpy_stems}:
                # A .rpyc with a .rpy next to it is covered by the .rpy.
                yield Path(root) / name


def game_builds_numbered_choices(game_dir: str | Path) -> bool:
    """True when a script of the game prefixes menu captions with a number."""
    base = Path(game_dir)
    if not base.is_dir():
        return False
    for path in _iter_game_scripts(base):
        try:
            if path.stat().st_size > _MAX_SOURCE_BYTES:
                continue
            data = path.read_bytes()
        except OSError:
            continue
        chunks = _rpyc_chunks(data) if path.suffix.lower() == ".rpyc" else (data,)
        for chunk in chunks:
            if b"caption" not in chunk:
                continue
            if _text_matches(chunk.decode("utf-8", errors="ignore")):
                return True
    return False


def render_hook() -> str:
    return '''# Auto-generated by RenLocalizer - numbered menu choices
# This game draws "1. <caption>" from a concatenated string, which Ren'Py
# cannot translate as a whole. Only the caption part is translated here.
init 998 python:
    import re as _rl_re

    _rl_numbered_re = _rl_re.compile(r"^(\\d+\\.\\s*)(.+)$", _rl_re.DOTALL)
    _rl_previous_replace_text = config.replace_text

    def _rl_numbered_choice_text(s):
        if _rl_previous_replace_text is not None:
            s = _rl_previous_replace_text(s)
        if not s or not s[0].isdigit():
            return s
        m = _rl_numbered_re.match(s)
        if m is None:
            return s
        translated = renpy.translation.translate_string(m.group(2))
        if translated == m.group(2):
            return s
        return m.group(1) + translated

    config.replace_text = _rl_numbered_choice_text
'''
